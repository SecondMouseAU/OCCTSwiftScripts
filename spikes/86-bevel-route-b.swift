// Spike 86: bevel gear Route B (revolved blank + circularPatternCut)
//
// Part of the BOSL2 bevel gear port epic (#84). Answers the question in issue
// #86: does a revolved cone-frustum blank survive N near-tangential
// circularPatternCut booleans, and if the resulting gear is valid, is its
// face count (especially per-tooth flank face count) better than Route A's
// loft (spikes/85-bevel-route-a.swift, #85)?
//
// Math ported from BOSL2's gears.scad `bevel_gear()` (lines 2486-2650), same
// scope as #85: straight/zerol teeth (spiral = 0), no backing, no bore,
// single gear, mate_teeth == teeth (45 degree symmetric miter pair). BOSL2 is
// BSD-2-Clause, Copyright 2017-2019 Revar Desmera:
// https://github.com/BelfrySCAD/BOSL2/blob/master/gears.scad
//
// `GearGeometry` and `slicePoint` below are copied UNCHANGED from
// spikes/85-bevel-route-a.swift (per #86's instruction to reuse Route A's
// ported math rather than re-derive it); this file cannot `import` that
// spike script (it is a standalone Sources/Script/main.swift payload, not a
// module), so the duplication is deliberate and its provenance is called out
// at each copied declaration.
//
// ── Construction (Route B) ──────────────────────────────────────────────────
// 1. Blank: a hollow cone-frustum shell, bounded radially by the outer
//    (addendum) cone and the root (dedendum) cone, spanning the same face
//    width Route A used. Built by revolving a 4-point trapezoid meridian
//    profile 360 degrees about the Z axis (Shape.revolve).
// 2. Tooth-space cutter: ONE gap wedge, lofted across the same slices+1
//    stations as Route A, across the same tooth pitch. The gap boundary is
//    generated by the *same* flank/root point machinery Route A's
//    `toothLocalProfile` uses (`flankPoint`/`radialPoint` below), evaluated
//    at a different angular offset: a tooth's half-angle at the base circle
//    is `flankOffset = pi/(2*teeth) + inv(alpha)` (BOSL2/standard involute
//    gear geometry: the pitch-circle half-angle pi/(2*teeth), corrected by
//    the involute roll angle inv(alpha) between the base and pitch circles).
//    The space between two teeth is bounded, by the gear's own periodic
//    mirror symmetry (reflecting through the gap's centerline swaps the two
//    teeth that bound it), by the SAME kind of curve at the complementary
//    offset `gapFlankOffset = pi/teeth - flankOffset = pi/(2*teeth) -
//    inv(alpha)`, but with the two flanks' `mirror` flags SWAPPED relative
//    to a tooth's own pairing: a tooth's flanks converge as radius grows,
//    a gap's flanks diverge, and `flankPoint`'s `mirror` argument is what
//    controls that growth direction. This is a one-line trig substitution
//    plus a mirror-flag swap, not a re-derivation of the involute or the
//    cone transform stack. The cutter is extended radially past both the
//    addendum and root circles (`radialClearance`) so the boolean cut
//    never grazes the blank's own boundary surfaces
//    tangentially, per #86's explicit instruction.
// 3. Pattern cut: one `blank.circularPatternCut(tool:axisPoint:axisDirection:
//    count:)` call, the same primitive `recipes/03-pipe-flange/main.swift`
//    already uses for its bolt circle.
//
// Both the blank revolve and the cutter loft are healed immediately after
// construction, carrying forward Spike 1's finding that `ThruSectionsBuilder`
// output is never `isValid` on its own but heals for free. `unified()` is
// also tried post-heal (docs/guides/cookbook/healing-and-validity.md's
// standard post-boolean cleanup) since patterning N near-identical cuts
// around a shared conical blank surface is exactly the kind of redundant
// coplanar/co-conical face split `ShapeUpgrade_UnifySameDomain` targets.
//
// If `circularPatternCut` fails outright (returns nil) or produces a shape
// that heals to something clearly wrong (volume far from Route A's for the
// same teeth/module), this file falls back to a manual sequential-cut loop
// (`diagnoseSequentialCuts`) that subtracts one tool copy at a time and
// records the first tooth index where `isValid` goes false or `analyze()`
// reports a self-intersection, so a failure has a specific, reportable
// locus rather than just "it returned nil".
//
// ── KNOWN LIMITATION, unresolved at spike close ─────────────────────────────
// `circularPatternCut` itself never failed and never produced a self-
// intersecting or free-edged result at any tooth count tested (16 through
// 60): that is the spike's headline finding, and it is solid. What did NOT
// get resolved in the time available is this file's own cutter geometry.
// A single boundary-point coincidence check (built, then deleted, during
// debugging) proved the gap curve's formula is exact at the pitch radius and
// within a few tenths of a millimeter of exact at the base circle and tip.
// That is too small an error to explain what the built gears actually look
// like: rendered previews show the surviving "teeth" as thin, disconnected
// blade-like remnants rather than a continuous toothed rim, and with any
// nonzero `radialClearance`, `Shape.volume` on the final pattern-cut result
// returns nil even though `isValid` is true and `analyze()` reports zero
// small edges, free edges, and self-intersections. Dropping the clearance to
// zero (i.e. letting the cutter graze the blank's own root/tip surfaces
// exactly, the tangency #86 explicitly warned against) makes the volume
// computable again but the cuts barely remove any material. Neither
// configuration produces a gear that matches Route A's dimensions or looks
// like the rendered gear the construction is supposed to produce. The most
// likely remaining cause, not chased further given the timebox, is that the
// wedge's own loft end caps at the two axial (face-width) stations end up
// exactly coplanar with the blank's own end caps by construction (both are
// built from the same affine meridian-line relationship), and whatever OCCT
// does with that tangency at the AXIAL ends, not the angular gap width,
// is producing the degenerate result. Reported plainly per #86's own
// "failure is still a result" framing: this is a real, specific, and
// reproducible defect in this spike's cutter, not a demonstrated weakness of
// `circularPatternCut` itself.
//
// Run:  swift run occtkit run spikes/86-bevel-route-b.swift
// (Spike 1's `swift run Script` workaround for issue #98 is no longer
// needed in this worktree; #98 is fixed and merged.)

